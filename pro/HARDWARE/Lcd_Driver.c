void Lcd_SetRegion(unsigned short int x_start,unsigned short int y_start,unsigned short int x_end,unsigned short int y_end)
{
    Lcd_WriteIndex(0x2a);
    Lcd_WriteData(0x00);
    Lcd_WriteData(x_start);
    Lcd_WriteData(0x00);
    Lcd_WriteData(x_end);

    Lcd_WriteIndex(0x2b);
    Lcd_WriteData(0x00);
    Lcd_WriteData(y_start+0);
    Lcd_WriteData(0x00);
    Lcd_WriteData(y_end);

    Lcd_WriteIndex(0x2c);
}

void Lcd_SetXY(unsigned short int x,unsigned short int y)
{
    Lcd_SetRegion(x,y,x,y);
}

void Gui_DrawPoint(unsigned short int x,unsigned short int y,unsigned short int Data)
{
    Lcd_SetRegion(x,y,x+1,y+1);
    LCD_WriteData_16Bit(Data);
}

unsigned int Lcd_ReadPoint(unsigned short int x,unsigned short int y)
{
    unsigned int Data;
    Lcd_SetXY(x,y);
    return Data;
}

void Lcd_Clear(unsigned short int Color)
{
    unsigned int i,m;
    Lcd_SetRegion(0,0,X_MAX_PIXEL-1,Y_MAX_PIXEL-1);
    Lcd_WriteIndex(0x2C);
    for(i=0;i<X_MAX_PIXEL;i++)
        for(m=0;m<Y_MAX_PIXEL;m++)
        {
            LCD_WriteData_16Bit(Color);
        }
}

void SPI_WriteData(unsigned char Data)
{
    unsigned char i=0;
    for(i=8;i>0;i--)
    {
        if(Data&0x80)
            LCD_SDA_SET;
        else
            LCD_SDA_CLR;

        LCD_SCL_CLR;
        LCD_SCL_SET;
        Data<<=1;
    }
}

void Lcd_WriteIndex(unsigned char Index)
{
    LCD_CS_CLR;
    LCD_RS_CLR;
    SPI_WriteData(Index);
    LCD_CS_SET;
}

void Lcd_WriteData(unsigned char Data)
{
    LCD_CS_CLR;
    LCD_RS_SET;
    SPI_WriteData(Data);
    LCD_CS_SET;
}

void LCD_WriteData_16Bit(unsigned short int Data)
{
   LCD_CS_CLR;
    LCD_RS_SET;
    SPI_WriteData(Data>>8);
    SPI_WriteData(Data);
    LCD_CS_SET;
}

void Lcd_WriteReg(unsigned char Index,unsigned char Data)
{
    Lcd_WriteIndex(Index);
    Lcd_WriteData(Data);
}

void Lcd_Reset(void)
{
    LCD_RST_CLR;
    HAL_Delay(100);
    LCD_RST_SET;
    HAL_Delay(50);
}


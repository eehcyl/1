void LCD_Show_Char(uint16_t x, uint16_t y, uint8_t ch)
{
    uint8_t i, j, temp;
    uint8_t index = 0;

    if(ch >= '0' && ch <= '9')
        index = ch - '0';
    else if(ch == ':')
        index = 10;
    else if(ch >= 'A' && ch <= 'Z')
        index = 11 + (ch - 'A');
    else if(ch >= 'a' && ch <= 'z')
        index = 37 + (ch - 'a');
    else if(ch == '%')        // ????
        index = 63;
    else if(ch == '.')        // ??????
        index = 64;           // ????????
    else if(ch == '-')
        index = 65;
    else
        return;

    // ????(??90?,??????)
    for(i = 0; i < 16; i++)
    {
        temp = ASCII_8x16[index][i];
        for(j = 0; j < 8; j++)
        {
            if(temp & 0x80)
                Gui_DrawPoint(x + i, y + (7 - j), WHITE);
            else
                Gui_DrawPoint(x + i, y + (7 - j), BLACK);
            temp <<= 1;
        }
    }
}

